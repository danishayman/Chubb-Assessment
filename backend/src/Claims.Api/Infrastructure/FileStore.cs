namespace Claims.Api.Infrastructure;

/// <summary>Where attachment bytes live. Local disk for the demo; blob storage (S3/Azure) in production.</summary>
public interface IFileStore
{
    Task SaveAsync(string key, Stream content, CancellationToken ct);
    Stream? OpenRead(string key);
    void Delete(string key);
}

public class LocalFileStore : IFileStore
{
    private readonly string _root;

    public LocalFileStore(IConfiguration config, IWebHostEnvironment env)
    {
        var path = config["Attachments:Path"] ?? "uploads";
        _root = Path.GetFullPath(Path.IsPathRooted(path) ? path : Path.Combine(env.ContentRootPath, path));
        Directory.CreateDirectory(_root);
    }

    public async Task SaveAsync(string key, Stream content, CancellationToken ct)
    {
        var path = Resolve(key);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        await using var file = new FileStream(path, FileMode.CreateNew, FileAccess.Write);
        await content.CopyToAsync(file, ct);
    }

    public Stream? OpenRead(string key)
    {
        var path = Resolve(key);
        return File.Exists(path) ? new FileStream(path, FileMode.Open, FileAccess.Read, FileShare.Read) : null;
    }

    public void Delete(string key)
    {
        var path = Resolve(key);
        if (File.Exists(path)) File.Delete(path);
    }

    // Keys are generated by us from GUIDs, but never trust a path: make sure it stays under the root.
    private string Resolve(string key)
    {
        var path = Path.GetFullPath(Path.Combine(_root, key));
        if (!path.StartsWith(_root + Path.DirectorySeparatorChar, StringComparison.OrdinalIgnoreCase))
            throw new InvalidOperationException("Invalid storage key.");
        return path;
    }
}

/// <summary>
/// Decides what a file really is from its first bytes. The browser's Content-Type and the file
/// extension are both under the user's control, so neither is trusted on its own.
/// </summary>
public static class FileSniffer
{
    private static readonly (string ContentType, string[] Extensions, byte[] Magic, int Offset)[] Known =
    [
        ("application/pdf", [".pdf"], "%PDF-"u8.ToArray(), 0),
        ("image/png", [".png"], [0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A], 0),
        ("image/jpeg", [".jpg", ".jpeg"], [0xFF, 0xD8, 0xFF], 0),
        ("image/webp", [".webp"], "WEBP"u8.ToArray(), 8),
    ];

    public const string AllowedDescription = "PDF, JPG, PNG or WEBP";

    public static string? Detect(ReadOnlySpan<byte> header, string fileName)
    {
        var ext = Path.GetExtension(fileName).ToLowerInvariant();
        foreach (var (type, exts, magic, offset) in Known)
        {
            if (header.Length >= offset + magic.Length && header.Slice(offset, magic.Length).SequenceEqual(magic))
                return exts.Contains(ext) ? type : null;
        }
        return null;
    }

    /// <summary>Strips any path and control characters and keeps the name a sensible length.</summary>
    public static string CleanFileName(string fileName)
    {
        var name = Path.GetFileName(fileName.Replace('\\', '/'));
        name = new string(name.Where(c => !char.IsControl(c) && c != '"').ToArray()).Trim();
        if (name.Length > 120)
            name = name[..(120 - Path.GetExtension(name).Length)] + Path.GetExtension(name);
        return string.IsNullOrWhiteSpace(name) ? "document" : name;
    }
}
